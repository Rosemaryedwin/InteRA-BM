# Clinical vs microbial detection
meta_clin_cols = [c for c in meta_enc.drop(columns=["label"], errors="ignore").columns if c in X_reduced.columns]
hex_like = re.compile(r"^[0-9a-f]{12,}$", re.IGNORECASE)

def feature_type(name):
    if name in meta_clin_cols: return "Clinical"
    return "Microbial" if hex_like.match(str(name)) else "Clinical"

# Taxonomy lookup (genus → else family → else Unclassified)
def extract_rank(tax_str, rank_code):
    m = re.search(fr"{rank_code}__([^;]+)", str(tax_str) if tax_raw is not None else "")
    if m:
        val = m.group(1).strip()
        if val and val.lower() not in {"na","unclassified","uncultured"}:
            return val
    return None

def tax_label(asv_id):
    if (tax_raw is None) or (str(asv_id) not in (tax_raw.index.astype(str))):
        return "Clinical Feature" if asv_id in meta_clin_cols else "Unclassified"
    tax_str = tax_raw.loc[str(asv_id), "Taxon"]
    g = extract_rank(tax_str, "g")
    if g: return g
    f = extract_rank(tax_str, "f")
    return f if f else "Unclassified"

# Group means for direction (on CLR scale)
mean_RA = X_reduced[y_vec==1].mean(axis=0)
mean_HC = X_reduced[y_vec==0].mean(axis=0)
def direction(name): return "Higher in RA" if mean_RA[name] > mean_HC[name] else "Higher in Healthy"

biomarker_df = pd.DataFrame({
    "Feature": feat_importance.index,
    "Feature_Type": [feature_type(f) for f in feat_importance.index],
    "Genus_or_Family": [tax_label(f) for f in feat_importance.index],
    "Importance": feat_importance.values,
    "Mean_RA": [mean_RA[f] for f in feat_importance.index],
    "Mean_Healthy": [mean_HC[f] for f in feat_importance.index],
    "Direction": [direction(f) for f in feat_importance.index]
}).sort_values("Importance", ascending=False).reset_index(drop=True)

