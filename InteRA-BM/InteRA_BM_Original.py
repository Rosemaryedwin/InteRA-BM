for fold, (tr_idx, val_idx) in enumerate(cv.split(X_train, y_train), 1):
    X_tr_cv, X_val_cv = X_train.iloc[tr_idx], X_train.iloc[val_idx]
    y_tr_cv, y_val_cv = y_train[tr_idx], y_train[val_idx]

    # Fit fresh RF inside each fold
    rf_cv = RandomForestClassifier(
        n_estimators=600, max_depth=15, min_samples_split=5, min_samples_leaf=1,
        max_features="sqrt", class_weight="balanced",
        random_state=RANDOM_STATE, n_jobs=-1
    )
    rf_cv.fit(X_tr_cv, y_tr_cv)

    # Calibrate inside the fold
    cal_cv = CalibratedClassifierCV(estimator=rf_cv, method="sigmoid", cv=3)
    cal_cv.fit(X_tr_cv, y_tr_cv)

    # Predict calibrated probabilities
    y_val_prob = cal_cv.predict_proba(X_val_cv)[:, 1]

    best_acc, best_thr = -1.0, 0.50
    for thr in thresholds:
        acc_thr = accuracy_score(y_val_cv, (y_val_prob >= thr).astype(int))
        if acc_thr > best_acc:
            best_acc, best_thr = acc_thr, thr

    best_thresholds.append(best_thr)
    fold_results.append((fold, best_thr, best_acc))
    print(f"Fold {fold}: Best thr={best_thr:.3f} | ACC={best_acc:.3f}")

