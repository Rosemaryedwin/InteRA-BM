# Replace ASV IDs with Genus/Family Names
def get_tax_label(asv_id):
    """Return Genus if available, else Family; otherwise original ID."""
    if asv_id not in tax_raw.index:
        return asv_id
    tax_str = str(tax_raw.loc[asv_id, "Taxon"])

    g = re.search(r"g__([^;]+)", tax_str)
    if g and g.group(1) not in ["", "NA", "uncultured", "unclassified"]:
        return g.group(1)

    f = re.search(r"f__([^;]+)", tax_str)
    if f and f.group(1) not in ["", "NA", "uncultured", "unclassified"]:
        return f.group(1)

    return asv_id

